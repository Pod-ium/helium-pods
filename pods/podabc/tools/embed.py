#!/usr/bin/env python3
"""Turns binary files into a C++ source with one array each (used by the
build: the assets end up in flash on the device).

  embed.py <out.cpp> <symbol> <file> [<symbol> <file>...]

Each file gives `extern const uint8_t <symbol>[]` and
`extern const uint32_t <symbol>_size`.
"""
import sys


def main():
    out, pairs = sys.argv[1], sys.argv[2:]
    if not pairs or len(pairs) % 2:
        sys.exit(__doc__)
    lines = ["// Generated by tools/embed.py: do not edit.", "#include <cstdint>", ""]
    for sym, path in zip(pairs[::2], pairs[1::2]):
        data = open(path, "rb").read()
        lines.append(f"extern const uint8_t {sym}[];")
        lines.append(f"extern const uint32_t {sym}_size;")
        lines.append(f"alignas(4) const uint8_t {sym}[] = {{")
        for i in range(0, len(data), 24):
            lines.append("".join(f"{b},".rjust(4) for b in data[i:i + 24]))
        lines.append("};")
        lines.append(f"const uint32_t {sym}_size = {len(data)};")
        lines.append("")
    with open(out, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
